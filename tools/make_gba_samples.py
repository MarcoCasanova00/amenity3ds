#!/usr/bin/env python3
"""Convert a break WAV into a 22050 Hz mono 16-bit C array for the GBA player.

Usage: make_gba_samples.py <break.wav> <ident> <out.c>
"""
import sys, os, wave

RATE = 22050

def load_mono(path):
    w = wave.open(path, 'rb')
    ch, sw, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    frames = []
    if sw == 2:
        for i in range(n):
            off = i * 2 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+2], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+2], 'little', signed=True)
                r = int.from_bytes(raw[off+2:off+4], 'little', signed=True)
                frames.append((l + r) // 2)
    elif sw == 3:
        for i in range(n):
            off = i * 3 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+3], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+3], 'little', signed=True)
                r = int.from_bytes(raw[off+3:off+6], 'little', signed=True)
                frames.append((l + r) // 2)
    else:
        raise SystemExit('unsupported width %d' % sw)
    return frames, rate

def resample(x, in_rate, out_rate):
    if in_rate == out_rate:
        return x
    ratio = in_rate / out_rate
    n_out = int(len(x) / ratio)
    out = [0] * n_out
    for i in range(n_out):
        pos = i * ratio
        i0 = int(pos)
        i1 = min(i0 + 1, len(x) - 1)
        frac = pos - i0
        out[i] = int(x[i0] * (1.0 - frac) + x[i1] * frac)
    return out

def main():
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    src, ident, out = sys.argv[1], sys.argv[2], sys.argv[3]
    frames, rate = load_mono(src)
    mono = resample(frames, rate, RATE)
    # soft normalize
    peak = max(abs(v) for v in mono) or 1
    g = 32760.0 / peak
    with open(out, 'w') as fh:
        fh.write('// Auto-generated by tools/make_gba_samples.py - do not edit.\n')
        fh.write('#include <stdint.h>\n\n')
        fh.write('const int16_t %s[] = {\n' % ident)
        for i in range(0, len(mono), 16):
            fh.write('    ' + ','.join(str(int(max(-32768, min(32767, v * g)))) for v in mono[i:i+16]) + ',\n')
        fh.write('};\n')
        fh.write('const int %s_len = %d;\n' % (ident, len(mono)))
    print('%s: %d samples @ %d Hz' % (ident, len(mono), RATE))

if __name__ == '__main__':
    main()
