#!/usr/bin/env python3
"""Convert a break WAV into a banked 4-bit wave-playback header for gbc_dnb.

Pipeline (mirrors GBDK's wav_sample tooling but starts from our 44.1kHz
breaks):  downmix -> mono, downsample to 8000 Hz, convert to unsigned 8-bit,
pack pairs of 4-bit samples into one byte, and cap the length so the array
fits a single MBC1 16KB ROM bank.

Usage:
  make_dnb_samples.py <break.wav> <ident> <out.h> [max_kib]
"""
import sys, os, wave, math

OUT_RATE = 8000
MAX_BYTES_DEFAULT = 12 * 1024   # 12 KiB -> 24576 samples -> ~3 s at 8 kHz

def load_mono(path):
    w = wave.open(path, 'rb')
    ch, sw, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    frames = []
    if sw == 2:
        for i in range(n):
            off = i * 2 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+2], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+2], 'little', signed=True)
                r = int.from_bytes(raw[off+2:off+4], 'little', signed=True)
                frames.append((l + r) // 2)
    elif sw == 3:
        for i in range(n):
            off = i * 3 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+3], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+3], 'little', signed=True)
                r = int.from_bytes(raw[off+3:off+6], 'little', signed=True)
                frames.append((l + r) // 2)
    else:
        raise SystemExit('unsupported sample width %d' % sw)
    return frames, rate

def resample(x, in_rate, out_rate):
    ratio = in_rate / out_rate
    n_out = int(len(x) / ratio)
    out = [0] * n_out
    for i in range(n_out):
        pos = i * ratio
        i0 = int(pos)
        i1 = min(i0 + 1, len(x) - 1)
        frac = pos - i0
        out[i] = int(x[i0] * (1.0 - frac) + x[i1] * frac)
    return out

def main():
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    src, ident, out = sys.argv[1], sys.argv[2], sys.argv[3]
    max_bytes = MAX_BYTES_DEFAULT
    if len(sys.argv) > 4:
        max_bytes = int(float(sys.argv[4]) * 1024)
    bank = 2
    if len(sys.argv) > 5:
        bank = int(sys.argv[5])

    frames, rate = load_mono(src)
    mono = resample(frames, rate, OUT_RATE)

    # to unsigned 8-bit (0..255) and pack 4-bit pairs
    bytes_out = []
    for i in range(0, len(mono) - 1, 2):
        hi = (mono[i] >> 8) + 128
        lo = (mono[i + 1] >> 8) + 128
        bytes_out.append(((hi & 0x0F) << 4) | (lo & 0x0F))
    bytes_out = bytes_out[:max_bytes]
    if not bytes_out:
        sys.exit('empty output')

    with open(out, 'w') as fh:
        fh.write('// Auto-generated by tools/make_dnb_samples.py - do not edit.\n')
        if bank != 0:
            fh.write('#pragma bank %d\n\n' % bank)
        else:
            fh.write('\n')
        fh.write('#include <gb/gb.h>\n\n')
        fh.write('const UINT8 %s[] = {\n' % ident)
        for i in range(0, len(bytes_out), 16):
            fh.write('    ' + ','.join('0x%x' % b for b in bytes_out[i:i+16]) + ',\n')
        fh.write('};\n')
    hdr = os.path.splitext(out)[0] + '.h'
    with open(hdr, 'w') as fh:
        fh.write('// Auto-generated by tools/make_dnb_samples.py - do not edit.\n')
        fh.write('#ifndef %s_H\n#define %s_H\n\n' % (ident.upper(), ident.upper()))
        fh.write('#include <gb/gb.h>\n')
        fh.write('extern const UINT8 %s[%d];\n\n' % (ident, len(bytes_out)))
        fh.write('#endif\n')
    print('%s: %d bytes (%d samples @ %d Hz)' % (ident, len(bytes_out), len(bytes_out) * 2, OUT_RATE))

if __name__ == '__main__':
    main()
