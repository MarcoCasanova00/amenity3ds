#!/usr/bin/env python3
"""Convert amen.wav (48kHz 24-bit stereo) into a 32kHz mono 16-bit C array.

This mirrors the conversion Amenity's build does at build time:
  - downmix stereo -> mono
  - downsample 48k -> 32k (linear interpolation)
  - DC removal
  - normalize peak to ~0.95 of full scale
Output: source/break.h with `break_pcm[]` (int16), BREAK_SAMPLE_RATE,
BREAK_LEN, BREAK_SLICE_LEN (one 8th-note slice), BREAK_SLICES (16).
"""

import sys, wave, struct, os

def wav_to_pcm(path):
    w = wave.open(path, 'rb')
    ch = w.getnchannels()
    sw = w.getsampwidth()
    rate = w.getframerate()
    frames = w.getnframes()
    raw = w.readframes(frames)
    w.close()
    assert ch == 2 and sw == 3, "expected 24-bit stereo"

    n = frames
    pcm = [0] * (n * 2)          # interleaved stereo int
    for i in range(n):
        off = i * 6
        l = int.from_bytes(raw[off:off+3], 'little', signed=True)
        r = int.from_bytes(raw[off+3:off+6], 'little', signed=True)
        pcm[i*2] = l
        pcm[i*2+1] = r
    return pcm, rate, n

def downmix(pcm, n):
    return [(pcm[i*2] + pcm[i*2+1]) // 2 for i in range(n)]

def downsample(m, in_rate, out_rate):
    ratio = in_rate / out_rate   # read step in input samples per output sample
    n_out = int(len(m) / ratio)
    out = [0] * n_out
    for i in range(n_out):
        pos = i * ratio
        i0 = int(pos)
        i1 = min(i0 + 1, len(m) - 1)
        frac = pos - i0
        out[i] = int(m[i0] * (1.0 - frac) + m[i1] * frac)
    return out

def dc_block(x, a=0.999):
    y_prev = 0.0
    x_prev = 0.0
    out = [0] * len(x)
    for i, v in enumerate(x):
        y = v - x_prev + a * y_prev
        x_prev = v
        y_prev = y
        out[i] = y
    return out

def normalize(x, target=0.95):
    peak = max(abs(v) for v in x) or 1
    scale = target * 32767.0 / peak
    return [int(max(-32768, min(32767, round(v * scale)))) for v in x]

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'assets/third-party/amen/amen.wav'
    out = sys.argv[2] if len(sys.argv) > 2 else 'source/break.h'
    OUT_RATE = 32000

    pcm, in_rate, n = wav_to_pcm(src)
    mono = downmix(pcm, n)
    mono32 = downsample(mono, in_rate, OUT_RATE)
    mono32 = dc_block(mono32)
    mono32 = normalize(mono32)

    slices = 16
    # Round loop length down to a whole multiple of `slices` slices.
    loop = (len(mono32) // slices) * slices
    mono32 = mono32[:loop]
    slice_len = loop // slices

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as f:
        f.write('// Auto-generated by tools/wav2c.py — do not edit.\n')
        f.write('// Source: %s (48kHz/24-bit stereo, two-bar Amen loop at 160 BPM)\n' % os.path.basename(src))
        f.write('#ifndef BREAK_H\n#define BREAK_H\n\n')
        f.write('#define BREAK_SAMPLE_RATE %d\n' % OUT_RATE)
        f.write('#define BREAK_LEN %d\n' % loop)
        f.write('#define BREAK_SLICES %d\n' % slices)
        f.write('#define BREAK_SLICE_LEN %d\n' % slice_len)
        f.write('static const short break_pcm[%d] = {\n' % loop)
        for i in range(0, loop, 16):
            f.write('    ' + ','.join(str(v) for v in mono32[i:i+16]) + ',\n')
        f.write('};\n\n#endif\n')

    print('wrote %s: %d frames @ %d Hz mono, slice=%d, slices=%d'
          % (out, loop, OUT_RATE, slice_len, slices))

if __name__ == '__main__':
    main()
