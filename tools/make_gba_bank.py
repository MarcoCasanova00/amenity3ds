#!/usr/bin/env python3
"""Generate the GBA break bank (samples.c + samples.h) from assets/breaks.

Usage: make_gba_bank.py <wav_dir> <out_base>
Writes <out_base>.c and <out_base>.h.
"""
import sys, os, wave

RATE = 22050
IDENTS = [('CLN086.wav', 'brk0'), ('CLN105.wav', 'brk1'),
          ('PRC095.wav', 'brk2'), ('PRC098.wav', 'brk3')]

def load_mono(path):
    w = wave.open(path, 'rb')
    ch, sw, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    frames = []
    if sw == 2:
        for i in range(n):
            off = i * 2 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+2], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+2], 'little', signed=True)
                r = int.from_bytes(raw[off+2:off+4], 'little', signed=True)
                frames.append((l + r) // 2)
    elif sw == 3:
        for i in range(n):
            off = i * 3 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+3], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+3], 'little', signed=True)
                r = int.from_bytes(raw[off+3:off+6], 'little', signed=True)
                frames.append((l + r) // 2)
    else:
        raise SystemExit('sampwidth %d' % sw)
    return frames, rate

def resample(x, in_rate, out_rate):
    if in_rate == out_rate:
        return x
    ratio = in_rate / out_rate
    n_out = int(len(x) / ratio)
    out = [0] * n_out
    for i in range(n_out):
        pos = i * ratio
        i0 = int(pos)
        i1 = min(i0 + 1, len(x) - 1)
        frac = pos - i0
        out[i] = int(x[i0] * (1.0 - frac) + x[i1] * frac)
    return out

def main():
    d = sys.argv[1]
    base = sys.argv[2]
    parts = []
    headers = []
    for fn, ident in IDENTS:
        frames, rate = load_mono(os.path.join(d, fn))
        mono = resample(frames, rate, RATE)
        peak = max(abs(v) for v in mono) or 1
        g = 32760.0 / peak
        body = []
        for i in range(0, len(mono), 16):
            body.append('    ' + ','.join(str(int(max(-32768, min(32767, v * g)))) for v in mono[i:i+16]) + ',\n')
        parts.append('const int16_t %s[] = {\n%s};\nconst int %s_len = %d;\n'
                     % (ident, ''.join(body), ident, len(mono)))
        headers.append('extern const int16_t %s[];\nextern const int %s_len;\n' % (ident, ident))
        print('%s: %d samples @ %d Hz' % (ident, len(mono), RATE))
    with open(base + '.c', 'w') as f:
        f.write('// Auto-generated by tools/make_gba_bank.py - do not edit.\n')
        f.write('#include <stdint.h>\n\n')
        f.write(''.join(parts))
    with open(base + '.h', 'w') as f:
        f.write('// Auto-generated by tools/make_gba_bank.py - do not edit.\n')
        f.write('#ifndef SAMPLES_H\n#define SAMPLES_H\n\n')
        f.write('#include <stdint.h>\n\n')
        f.write(''.join(headers))
        f.write('\n#endif\n')

if __name__ == '__main__':
    main()
