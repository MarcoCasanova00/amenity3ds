#!/usr/bin/env python3
"""Build source/break_bank.h from every WAV in assets/breaks/.

Each break is converted to 44.1 kHz mono 16-bit (DC-blocked, normalized to
~0.95), then its loop length is rounded down to a whole multiple of 16 slices.
The engine slices each break into its 16 eighth-note pieces, exactly like the
original Amenity firmware does for its single break.
"""
import os, sys, wave, re

BANK_SR = 44100
SLICES = 16

def bpm_from_name(name):
    m = re.search(r'(\d{2,3})', name)
    return int(m.group(1)) if m else 0

def load_pcm(path):
    w = wave.open(path, 'rb')
    ch, sw, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
    n = w.getnframes()
    raw = w.readframes(n)
    w.close()
    assert sw == 2 or sw == 3, "expected 16/24-bit WAV"
    frames = []
    if sw == 2:
        for i in range(n):
            off = i * 2 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+2], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+2], 'little', signed=True)
                r = int.from_bytes(raw[off+2:off+4], 'little', signed=True)
                frames.append((l + r) // 2)
    else:
        for i in range(n):
            off = i * 3 * ch
            if ch == 1:
                frames.append(int.from_bytes(raw[off:off+3], 'little', signed=True))
            else:
                l = int.from_bytes(raw[off:off+3], 'little', signed=True)
                r = int.from_bytes(raw[off+3:off+6], 'little', signed=True)
                frames.append((l + r) // 2)
    return frames, rate, n

def resample(x, in_rate, out_rate):
    if in_rate == out_rate:
        return x
    ratio = in_rate / out_rate
    n_out = int(len(x) / ratio)
    out = [0] * n_out
    for i in range(n_out):
        pos = i * ratio
        i0 = int(pos)
        i1 = min(i0 + 1, len(x) - 1)
        frac = pos - i0
        out[i] = int(x[i0] * (1.0 - frac) + x[i1] * frac)
    return out

def dc_block(x, a=0.999):
    yp = xp = 0.0
    out = [0] * len(x)
    for i, v in enumerate(x):
        y = v - xp + a * yp
        xp, yp = v, y
        out[i] = y
    return out

def normalize(x, target=0.95):
    peak = max(abs(v) for v in x) or 1
    s = target * 32767.0 / peak
    return [int(max(-32768, min(32767, round(v * s)))) for v in x]

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'assets/breaks'
    out = sys.argv[2] if len(sys.argv) > 2 else 'source/break_bank.h'

    wavs = sorted(f for f in os.listdir(src) if f.lower().endswith('.wav'))
    if not wavs:
        sys.exit('no WAV files found in %s' % src)

    names = []
    offsets = []
    lengths = []
    slices = []
    allpcm = []
    total = 0
    for f in wavs:
        path = os.path.join(src, f)
        name = os.path.splitext(f)[0]
        frames, rate, n = load_pcm(path)
        mono = resample(frames, rate, BANK_SR)
        mono = dc_block(mono)
        mono = normalize(mono)
        loop = (len(mono) // SLICES) * SLICES
        mono = mono[:loop]
        sl = loop // SLICES
        names.append(name)
        offsets.append(total)
        lengths.append(loop)
        slices.append(sl)
        allpcm.extend(mono)
        total += loop
        print(' %-8s %6d frames @ %dHz  slice=%d (16 slices)' % (name, loop, BANK_SR, sl))

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as fh:
        fh.write('// Auto-generated by tools/wav2bank.py - do not edit.\n')
        fh.write('#ifndef BREAK_BANK_H\n#define BREAK_BANK_H\n\n')
        fh.write('#define BANK_SR %d\n' % BANK_SR)
        fh.write('#define BANK_COUNT %d\n' % len(names))
        fh.write('#define BANK_SLICES %d\n\n' % SLICES)
        fh.write('#define BANK_TOTAL %d\n\n' % total)
        fh.write('typedef struct {\n\tconst char* name;\n\tint off;\n\tint len;\n\tint slice_len;\n\tint bpm;\n} BankEntry;\n\n')
        fh.write('static const short bank_pcm[%d] = {\n' % total)
        for i in range(0, total, 16):
            fh.write('    ' + ','.join(str(v) for v in allpcm[i:i+16]) + ',\n')
        fh.write('};\n\n')
        fh.write('static const BankEntry bank_entries[BANK_COUNT] = {\n')
        for i in range(len(names)):
            fh.write('    {"%s", %d, %d, %d, %d},\n' % (names[i], offsets[i], lengths[i], slices[i], bpm_from_name(names[i])))
        fh.write('};\n\n#endif\n')

    print('wrote %s: %d breaks, %d total frames' % (out, len(names), total))

if __name__ == '__main__':
    main()
