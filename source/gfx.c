static int glyph_index(char c) {
	if (c >= '0' && c <= '9') return c - '0';
	if (c >= 'A' && c <= 'Z') return 10 + (c - 'A');
	switch (c) {
		case ':': return 36;
		case '.': return 37;
		case '-': return 38;
		case '/': return 39;
		default: return 40 - 1; /* space for anything else */
	}
}

void gfx_clear(u16* fb, int stride, int w, int h, u16 color) {
	for (int y = 0; y < h; y++) {
		u16* row = fb + y * stride;
		for (int x = 0; x < w; x++) row[x] = color;
	}
}

void gfx_fill(u16* fb, int stride, int x, int y, int w, int h, u16 color) {
	for (int yy = y; yy < y + h; yy++) {
		if (yy < 0) continue;
		u16* row = fb + yy * stride;
		for (int xx = x; xx < x + w; xx++) {
			if (xx >= 0) row[xx] = color;
		}
	}
}

void gfx_rect(u16* fb, int stride, int x, int y, int w, int h, u16 color) {
	gfx_fill(fb, stride, x, y, w, 1, color);
	gfx_fill(fb, stride, x, y + h - 1, w, 1, color);
	gfx_fill(fb, stride, x, y, 1, h, color);
	gfx_fill(fb, stride, x + w - 1, y, 1, h, color);
}

void gfx_char(u16* fb, int stride, int x, int y, char c, u16 fg, u16 bg) {
	const unsigned char* g = FONT[glyph_index(c)];
	for (int row = 0; row < 7; row++) {
		u16* p = fb + (y + row) * stride + x;
		unsigned char bits = g[row];
		for (int col = 0; col < 5; col++) {
			p[col] = (bits & (1 << (4 - col))) ? fg : bg;
		}
	}
}

void gfx_str(u16* fb, int stride, int x, int y, const char* s, u16 fg, u16 bg) {
	while (*s) {
		gfx_char(fb, stride, x, y, *s, fg, bg);
		x += 6;
		s++;
	}
}

int gfx_strw(const char* s) {
	int w = 0;
	while (*s) { w += 6; s++; }
	return w;
}

void gfx_bar(u16* fb, int stride, int x, int y, int w, int h, float frac, u16 color) {
	int fw = (int)(w * frac);
	if (fw < 0) fw = 0;
	if (fw > w) fw = w;
	gfx_rect(fb, stride, x, y, w, h, gfx_rgb(60, 60, 60));
	if (fw > 0) gfx_fill(fb, stride, x, y, fw, h, color);
}
